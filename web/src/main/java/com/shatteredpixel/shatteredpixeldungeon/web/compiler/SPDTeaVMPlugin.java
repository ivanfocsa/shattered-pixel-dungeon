package com.shatteredpixel.shatteredpixeldungeon.web.compiler;

import org.teavm.dependency.AbstractDependencyListener;
import org.teavm.dependency.DependencyAgent;
import org.teavm.vm.spi.TeaVMHost;
import org.teavm.vm.spi.TeaVMPlugin;

import java.io.BufferedReader;
import java.io.IOException;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;

/**
 * Build-time only (used by the TeaVM compiler, never shipped in the game).
 * TeaVM only lets Class.forName() return classes that were already known when forName
 * was first analysed. Saves restore objects by class name, so we make every game class
 * known right at the start of the analysis (list generated by the web/build.gradle).
 */
public class SPDTeaVMPlugin implements TeaVMPlugin {

	@Override
	public void install(TeaVMHost host) {
		host.add(new AbstractDependencyListener() {
			@Override
			public void started(DependencyAgent agent) {
				try (InputStream in = SPDTeaVMPlugin.class.getResourceAsStream("/spd-classes.txt")) {
					if (in == null) throw new IllegalStateException("spd-classes.txt not found on the TeaVM classpath");
					BufferedReader reader = new BufferedReader(new InputStreamReader(in, StandardCharsets.UTF_8));
					String line;
					while ((line = reader.readLine()) != null) {
						line = line.trim();
						if (!line.isEmpty()) agent.linkClass(line);
					}
				} catch (IOException e) {
					throw new RuntimeException(e);
				}
			}
		});
	}
}
